CREATE TABLE IF NOT EXISTS translation_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, entity_type text NOT NULL, entity_id bigint NOT NULL, version integer NOT NULL,
 editor_id bigint REFERENCES app_user(id) ON DELETE SET NULL, editor_name text NOT NULL, before jsonb NOT NULL, after jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_translation_audit_entity_type ON translation_audit(entity_type);
CREATE INDEX IF NOT EXISTS ix_translation_audit_entity_id ON translation_audit(entity_id);
CREATE OR REPLACE FUNCTION protect_human_translation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF current_setting('app.translation_edit', true) IS DISTINCT FROM 'on' THEN
   IF OLD.human_modified THEN RETURN OLD; END IF;
   IF NEW.name_ko IS NOT DISTINCT FROM OLD.name_ko AND NEW.short_name_ko IS NOT DISTINCT FROM OLD.short_name_ko THEN RETURN OLD; END IF;
 END IF;
 NEW.version := OLD.version + 1;
 NEW.updated_at := now();
 RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER league_translation_protect BEFORE UPDATE ON league_translation FOR EACH ROW EXECUTE FUNCTION protect_human_translation();
CREATE OR REPLACE TRIGGER team_translation_protect BEFORE UPDATE ON team_translation FOR EACH ROW EXECUTE FUNCTION protect_human_translation();
CREATE OR REPLACE TRIGGER player_translation_protect BEFORE UPDATE ON player_translation FOR EACH ROW EXECUTE FUNCTION protect_human_translation();
CREATE OR REPLACE TRIGGER coach_translation_protect BEFORE UPDATE ON coach_translation FOR EACH ROW EXECUTE FUNCTION protect_human_translation();

