CREATE TABLE IF NOT EXISTS management_run (
 id text PRIMARY KEY, status text NOT NULL, actor_id bigint REFERENCES app_user(id) ON DELETE SET NULL,
 payload jsonb NOT NULL, cancel_requested_at timestamptz, heartbeat_at timestamptz NOT NULL DEFAULT now(), created_at timestamptz NOT NULL DEFAULT now()
);
