test('mobile and dark layouts keep the query and results within the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/search')
  await expect(page.getByRole('button', { name: '검색하기' })).toBeVisible()
  await page.screenshot({ path: '/private/tmp/benchmark-search-mobile.png' })
  await page.getByRole('button', { name: /조건으로 좁히기/ }).click()
  await expect(page.getByRole('heading', { name: '조건에 맞는 선수' })).toBeVisible()
  expect(await page.locator('.search-page').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  const lightBackground = await page.locator('.search-page').evaluate(el => getComputedStyle(el).backgroundImage)
  await page.getByRole('button', { name: '테마 토글' }).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await expect(page.locator('html')).toHaveCSS('opacity', '1')
  expect(await page.locator('.search-page').evaluate(el => getComputedStyle(el).backgroundImage)).not.toBe(lightBackground)
  await page.screenshot({ path: '/private/tmp/benchmark-search-mobile-dark.png' })
})
