test('glass search starts on one line, grows with input and shrinks when cleared', async ({ page }) => {
  await page.goto('/search')
  const input = page.getByRole('textbox', { name: '궁금한 축구 기록', exact: true })
  await expect(input).toBeVisible()
  const height = () => input.evaluate(el => el.getBoundingClientRect().height)
  await expect.poll(height).toBe(26)
  await input.fill('프리미어리그 선수들의 출전 시간과 득점 기록을 비교해서 알려주세요. '.repeat(10))
  await expect.poll(height).toBeGreaterThan(26)
  await page.screenshot({ path: '/private/tmp/benchmark-search-glass-expanded.png' })
  await input.fill('도움 순위')
  await expect.poll(height).toBe(26)
  await input.press('Shift+Enter')
  await expect.poll(height).toBe(52)
  await expect(page.getByRole('region', { name: '검색 응답' })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await input.fill('선수 기록 '.repeat(80))
  await expect.poll(height).toBe(182)
  await input.fill('')
  await expect.poll(height).toBe(26)
  expect(await page.locator('.search-page').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
})

test('free input stays honest about the mock; examples show results and editable conditions', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/search')
  await expect(page.getByRole('button', { name: '검색하기' })).toBeDisabled()
  await page.screenshot({ path: '/private/tmp/benchmark-search-desktop.png' })
  await page.getByRole('textbox', { name: '궁금한 축구 기록', exact: true }).fill('아스널의 홈 경기 기록이 궁금해')
  await page.getByRole('textbox', { name: '궁금한 축구 기록', exact: true }).press('Enter')
  await expect(page.getByRole('heading', { name: '입력한 질문을 확인했어요' })).toBeVisible()
  await expect(page.getByRole('table')).toHaveCount(0)
  await page.getByRole('button', { name: /기록으로 찾기/ }).click()
  await expect(page.getByRole('heading', { name: '도움 순위', exact: true })).toBeVisible()
  await expect(page.locator('tbody tr')).toHaveCount(3)
  await page.getByRole('button', { name: '조건 수정' }).click()
  await page.getByLabel('시즌', { exact: true }).selectOption('2025/26')
  await page.getByRole('button', { name: '적용', exact: true }).click()
  await expect(page.locator('.conditions')).toContainText('2025/26')
  await page.screenshot({ path: '/private/tmp/benchmark-search-results.png' })
  await page.getByRole('button', { name: '새 검색' }).click()
  await expect(page.getByRole('textbox', { name: '궁금한 축구 기록', exact: true })).toHaveValue('')
  await expect(page.getByRole('table')).toHaveCount(0)
  expect(errors).toEqual([])
})

