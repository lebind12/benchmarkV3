import { expect, test } from '@playwright/test'

test('long searches cycle through messages and reset the cycle after cancellation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install()
  await page.goto('/search')
  await page.getByText('목업 상태 살펴보기', { exact: true }).click()
  await page.getByLabel('긴 검색 미리보기 (18초)').check()
  await page.getByRole('button', { name: '순위', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('기록을 찾고 있어요')
  for (const message of ['궁금한 기록까지, 잠시만요', '검색이 진행 중이에요', '조금만 더 기다려 주세요', '아직 검색 중이에요', '기다려 주셔서 고마워요', '기록을 찾고 있어요']) {
    await page.clock.fastForward(2800)
    await page.clock.runFor(50)
    await expect(page.getByRole('status')).toContainText(message)
  }
  await page.getByRole('button', { name: '새 검색' }).click()
  await page.clock.fastForward(20000)
  await expect(page.getByRole('status')).toHaveCount(0)
  await expect(page.getByRole('region', { name: '검색 응답' })).toHaveCount(0)
  await page.getByRole('button', { name: '순위', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('기록을 찾고 있어요')
  await page.getByRole('button', { name: '새 검색' }).click()
})

test('search shows progress, prevents duplicate submissions, then reveals the results', async ({ page }) => {
  await page.goto('/search')
  await page.getByRole('button', { name: /기록으로 찾기/ }).click()
  await expect(page.getByRole('status')).toContainText('기록을 찾고 있어요')
  await expect(page.getByRole('button', { name: '검색하기' })).toBeDisabled()
  await expect(page.getByRole('textbox')).toHaveAttribute('readonly')
  await expect(page.getByRole('table')).toHaveCount(0)
  await page.screenshot({ path: '/private/tmp/benchmark-search-loading.png' })
  await expect(page.getByRole('heading', { name: '도움 순위', exact: true })).toBeVisible()
  await expect(page.getByRole('status')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '검색하기' })).toBeEnabled()
  await page.getByRole('button', { name: '검색하기' }).click()
  await expect(page.getByRole('status')).toBeVisible()
  await page.getByRole('button', { name: '새 검색' }).click()
  await expect(page.getByRole('textbox')).toHaveValue('')
  await expect(page.getByRole('status')).toHaveCount(0)
  // A cancelled mock completion must not bring back stale results.
  await expect(page.getByRole('region', { name: '검색 응답' })).toHaveCount(0)
  await page.waitForTimeout(1000)
  await expect(page.getByRole('region', { name: '검색 응답' })).toHaveCount(0)
})

