for (const mode of ['desktop', 'mobile', 'dark', 'reduced-motion']) test(`${mode} layout, scroll and screenshot`, async ({ page }) => {
  if (mode === 'mobile') await page.setViewportSize({ width: 390, height: 844 })
  if (mode === 'dark') await page.getByTestId('theme-toggle').click()
  if (mode === 'reduced-motion') await page.emulateMedia({ reducedMotion: 'reduce' })
  await scenario(page, 'scheduled')
  await page.getByRole('button', { name: '다음 추천 경기', exact: true }).click()
  await page.locator('.hp-team__crest').first().evaluate(el => el.getAnimations().forEach(a => a.finish()))
  await page.locator('.hp-team__crest').last().evaluate(el => el.getAnimations().forEach(a => a.finish()))
  expect(await page.locator('.hp-page').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: `../out/home-preview/${mode}.png` })
  await page.locator('.hp-points').scrollIntoViewIfNeeded()
  await expect.poll(() => page.locator('.hp-analysis-grid').evaluate(el => Number(getComputedStyle(el).opacity))).toBeGreaterThan(.99)
  await page.screenshot({ path: `../out/home-preview/${mode}-preview.png` })
  await page.locator('.hp-sources').scrollIntoViewIfNeeded()
  await expect(page.locator('.hp-sources')).toBeVisible()
  await expect.poll(() => page.locator('.hp-sources').evaluate(el => Number(getComputedStyle(el).opacity))).toBeGreaterThan(.99)
  await page.screenshot({ path: `../out/home-preview/${mode}-sources.png` })
  if (mode === 'reduced-motion') expect(await page.locator('.hp-team__crest').first().evaluate(el => getComputedStyle(el).animationName)).toBe('none')
})

