import { test, expect, type Page } from '@playwright/test'
const errors: string[] = []
const apiRequests: string[] = []
async function tools(page: Page) { if (!await page.locator('.hp-tools').getAttribute('open').then(v => v !== null)) await page.getByText('평가 도구', { exact: true }).click() }
async function scenario(page: Page, value: string) { await tools(page); await page.getByLabel('경기 상황', { exact: true }).selectOption(value); await page.getByText('평가 도구', { exact: true }).click() }
test.beforeEach(async ({ page }) => {
  errors.length = 0; apiRequests.length = 0
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (new URL(r.url()).pathname.startsWith('/api/')) apiRequests.push(r.url()) })
  await page.goto('/home/mock')
})
test.afterEach(() => { expect(errors).toEqual([]); expect(apiRequests).toEqual([]) })
test('JSON controls render edited structured content and reject invalid data without replacing the preview', async ({ page }) => {
  await tools(page)
  await page.locator('.hp-json-tools summary').click()
  const textarea = page.getByLabel('프리뷰 JSON', { exact: true })
  const json = JSON.parse(await textarea.inputValue())
  json.analysis.summary.data.text = 'JSON에서 변경한 경기 전망'
  json.analysis.ai_prediction.data.home_goals = 3
  json.analysis.ai_prediction.data.away_goals = 2
  await textarea.fill(JSON.stringify(json))
  await page.getByRole('button', { name: 'JSON 적용', exact: true }).click()
  await expect(page.locator('.hp-lead')).toHaveText('JSON에서 변경한 경기 전망')
  await expect(page.locator('.hp-prediction__score')).toHaveText('3:2')
  json.sources[0].fixture_id = 123
  await textarea.fill(JSON.stringify(json))
  await page.getByRole('button', { name: 'JSON 적용', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('경기 ID')
  await expect(page.locator('.hp-lead')).toHaveText('JSON에서 변경한 경기 전망')
  await page.getByText('평가 도구', { exact: true }).click()
})
