import { test, expect } from '@playwright/test'
test.skip(process.env.HOME_PREVIEW_L3 !== '1', 'Requires explicitly prepared isolated home-preview API/DB')
test('isolated API and DB publication reaches the real main page', async ({ page }) => {
  const errors: string[] = []
  const newApiReads: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/recommendations|\/prematch/.test(request.url())) newApiReads.push(request.url()) })
  await page.goto('/')
  const home = page.getByTestId('home-preview-real')
  await expect(home.getByTestId('selected-preview')).toHaveAttribute('data-fixture-id', '1557444')
  await home.locator('.hp-match-strip button[data-fixture-id="1557445"]').click()
  await expect(home.getByTestId('selected-preview')).toHaveAttribute('data-fixture-id', '1557445')
  await expect(home.locator('.hp-preview-empty')).toHaveCount(0)
  await expect(home.locator('#preview-injuries')).toContainText('API-Football')
  await expect(home.locator('#preview-odds')).toContainText('Bet365')
  await expect(home.locator('.hp-form tbody tr')).toHaveCount(10)
  await expect(home.locator('.hp-lead')).not.toContainText('샘플')
  await expect(home.locator('.hp-tools')).toHaveCount(0)
  await home.locator('.hp-sources').scrollIntoViewIfNeeded()
  await page.screenshot({ path: '../out/home-preview/real-main-db-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await home.locator('#preview-form').scrollIntoViewIfNeeded()
  expect(await page.locator('.candidate-page').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  expect(await home.locator('.hp-form th').evaluateAll(cells => cells.every(cell => cell.getBoundingClientRect().right <= window.innerWidth))).toBe(true)
  await page.screenshot({ path: '../out/home-preview/real-main-db-mobile.png' })
  expect(errors).toEqual([])
  expect(newApiReads.filter(url => url.includes('recommendations'))).toHaveLength(1)
  expect(newApiReads.filter(url => url.includes('/prematch'))).toHaveLength(2)
})
